"""Generate Python / Go / TypeScript contract types from packages/shared (GUARDHUB_STANDARDS §7.4).

Sources: finding.schema.json + check-ids.json. Outputs are committed; CI runs `--check` and fails
when they are stale. The generator only supports the JSON-Schema subset used by finding.schema.json
(objects, strings, string enums, string maps, local $ref), and fails loudly on anything else.

Usage:  python packages/shared/scripts/gen_types.py [--check]
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SHARED = ROOT / "packages" / "shared"
OUT_PY = ROOT / "apps" / "api" / "guardhub_api" / "findings" / "contract_gen.py"
OUT_GO = ROOT / "apps" / "scanner" / "internal" / "evidence" / "contract_gen.go"
OUT_TS = ROOT / "apps" / "web" / "lib" / "contract.gen.ts"

HEADER = "Code generated by packages/shared/scripts/gen_types.py. DO NOT EDIT."


def _load() -> tuple[dict, dict]:
    schema = json.loads((SHARED / "finding.schema.json").read_text(encoding="utf-8"))
    catalog = json.loads((SHARED / "check-ids.json").read_text(encoding="utf-8"))
    return schema, catalog


def _repo_ids(catalog: dict) -> list[str]:
    targets = {c["id"]: c.get("target", "site") for c in catalog["checks"]}
    bad = {i: t for i, t in targets.items() if t not in ("site", "repo")}
    if bad:
        raise SystemExit(f"check-ids.json: unknown target {bad}")
    return [i for i, t in targets.items() if t == "repo"]


def _camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def _objects(schema: dict) -> list[tuple[str, dict]]:
    """Return (TypeName, objectSchema) for $defs first, then the root type."""
    out = [(name, sub) for name, sub in schema.get("$defs", {}).items()]
    out.append(("Finding", schema))
    for name, sub in out:
        if sub.get("type") != "object":
            raise SystemExit(f"unsupported schema type for {name}")
    return out


def _kind(prop: dict) -> str:
    if "$ref" in prop:
        return "ref:" + prop["$ref"].split("/")[-1]
    if prop.get("type") == "string" and "enum" in prop:
        return "enum"
    if prop.get("type") == "string":
        return "string"
    if prop.get("type") == "object" and prop.get("additionalProperties", {}).get("type") == "string":
        return "strmap"
    raise SystemExit(f"unsupported property schema: {prop}")


def _severities(schema: dict) -> list[str]:
    return list(schema["properties"]["severity"]["enum"])


def _evidence_kinds(schema: dict) -> list[str]:
    return list(schema["$defs"]["Evidence"]["properties"]["kind"]["enum"])


# --------------------------------------------------------------------------- python


def gen_python(schema: dict, catalog: dict) -> str:
    lines = [
        f'"""{HEADER}',
        "",
        "Contract types derived from packages/shared/finding.schema.json and check-ids.json.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Literal",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "Severity = Literal[" + ", ".join(repr(s) for s in _severities(schema)) + "]",
        "EvidenceKind = Literal[" + ", ".join(repr(s) for s in _evidence_kinds(schema)) + "]",
        "",
    ]
    for name, obj in _objects(schema):
        cls = "RawFinding" if name == "Finding" else name
        lines += ["", f"class {cls}(BaseModel):", f'    """{obj.get("description", name)}"""', ""]
        lines.append('    model_config = ConfigDict(extra="forbid", frozen=True)')
        lines.append("")
        for pname, prop in obj["properties"].items():
            kind = _kind(prop)
            args: list[str] = []
            if "pattern" in prop:
                args.append(f"pattern={prop['pattern']!r}")
            if "maxLength" in prop:
                args.append(f"max_length={prop['maxLength']}")
            if kind == "enum":
                typ = "Severity" if pname == "severity" else "EvidenceKind"
            elif kind == "string":
                typ = "str"
            elif kind == "strmap":
                typ = "dict[str, str]"
            else:
                typ = kind.split(":", 1)[1]
            field = f"Field({', '.join(args)})" if args else None
            lines.append(f"    {pname}: {typ}" + (f" = {field}" if field else ""))
    lines += ["", ""]
    lines.append("CHECK_FINDING_KEYS: dict[str, dict[str, Severity]] = {")
    for check in catalog["checks"]:
        lines.append(f"    {check['id']!r}: {{")
        for fk in check["finding_keys"]:
            lines.append(f"        {fk['key']!r}: {fk['severity']!r},")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    lines.append("CHECK_IDS: tuple[str, ...] = tuple(CHECK_FINDING_KEYS)")
    lines.append('# Checks that scan a connected repository (check-ids.json "target": "repo", ADR-0006).')
    repo = _repo_ids(catalog)
    lines.append("REPO_CHECK_IDS: tuple[str, ...] = (" + ", ".join(repr(i) for i in repo) + ("," if len(repo) == 1 else "") + ")")
    lines.append("SITE_CHECK_IDS: tuple[str, ...] = tuple(c for c in CHECK_IDS if c not in REPO_CHECK_IDS)")
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- go


def gen_go(schema: dict, catalog: dict) -> str:
    lines = [
        f"// {HEADER}",
        "",
        "package evidence",
        "",
        "// Severity is the finding severity level (finding.schema.json#/properties/severity).",
        "type Severity string",
        "",
        "const (",
    ]
    for s in _severities(schema):
        lines.append(f'\tSeverity{_camel(s)} Severity = "{s}"')
    lines += [")", "", "// Kind is the evidence kind (finding.schema.json#/$defs/Evidence/properties/kind).", "type Kind string", "", "const ("]
    for k in _evidence_kinds(schema):
        lines.append(f'\tKind{_camel(k)} Kind = "{k}"')
    lines += [")", ""]
    for name, obj in _objects(schema):
        lines.append(f"// {name}: {obj.get('description', name).split('. ')[0].rstrip('.')}.")
        lines.append(f"type {name} struct {{")
        for pname, prop in obj["properties"].items():
            kind = _kind(prop)
            if kind == "enum":
                typ = "Severity" if pname == "severity" else "Kind"
            elif kind == "string":
                typ = "string"
            elif kind == "strmap":
                typ = "map[string]string"
            else:
                typ = kind.split(":", 1)[1]
            lines.append(f'\t{_camel(pname).replace("Id", "ID")} {typ} `json:"{pname}"`')
        lines += ["}", ""]
    lines.append("// Check ids from check-ids.json.")
    lines.append("const (")
    for check in catalog["checks"]:
        lines.append(f'\tCheck{_camel(check["id"])} = "{check["id"]}"')
    lines += [")", ""]
    lines.append("// FindingKeys maps check id -> finding key -> default severity (check-ids.json).")
    lines.append("var FindingKeys = map[string]map[string]Severity{")
    for check in catalog["checks"]:
        lines.append(f'\t"{check["id"]}": {{')
        for fk in check["finding_keys"]:
            lines.append(f'\t\t"{fk["key"]}": Severity{_camel(fk["severity"])},')
        lines.append("\t},")
    lines += ["}", ""]
    lines.append('// RepoChecks holds the ids of checks that scan a connected repository (check-ids.json "target": "repo").')
    lines.append("var RepoChecks = map[string]bool{")
    for i in _repo_ids(catalog):
        lines.append(f'\t"{i}": true,')
    lines += ["}", ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------- typescript


def gen_ts(schema: dict, catalog: dict) -> str:
    lines = [
        f"// {HEADER}",
        "",
        "export type Severity = " + " | ".join(f'"{s}"' for s in _severities(schema)) + ";",
        "export type EvidenceKind = " + " | ".join(f'"{k}"' for k in _evidence_kinds(schema)) + ";",
        "",
        "export const SEVERITIES: readonly Severity[] = [" + ", ".join(f'"{s}"' for s in _severities(schema)) + "];",
        "",
    ]
    for name, obj in _objects(schema):
        tname = "RawFinding" if name == "Finding" else name
        lines.append(f"export interface {tname} {{")
        for pname, prop in obj["properties"].items():
            kind = _kind(prop)
            if kind == "enum":
                typ = "Severity" if pname == "severity" else "EvidenceKind"
            elif kind == "string":
                typ = "string"
            elif kind == "strmap":
                typ = "Record<string, string>"
            else:
                typ = kind.split(":", 1)[1]
            lines.append(f"  {pname}: {typ};")
        lines += ["}", ""]
    ids = [c["id"] for c in catalog["checks"]]
    lines.append("export const CHECK_IDS = [" + ", ".join(f'"{i}"' for i in ids) + "] as const;")
    lines.append("export type CheckId = (typeof CHECK_IDS)[number];")
    repo = _repo_ids(catalog)
    lines.append('/** Checks that scan a connected repository (check-ids.json "target": "repo"). */')
    lines.append("export const REPO_CHECK_IDS: readonly CheckId[] = [" + ", ".join(f'"{i}"' for i in repo) + "];")
    lines.append(
        "export const SITE_CHECK_IDS: readonly CheckId[] = ["
        + ", ".join(f'"{i}"' for i in ids if i not in repo)
        + "];"
    )
    lines.append("")
    return "\n".join(lines)


def _gofmt(src: str) -> str:
    gofmt = shutil.which("gofmt")
    if gofmt is None:
        raise SystemExit("gofmt not found on PATH (needed to format generated Go)")
    return subprocess.run([gofmt], input=src, capture_output=True, text=True, check=True, encoding="utf-8").stdout


def main() -> int:
    schema, catalog = _load()
    outputs = {
        OUT_PY: gen_python(schema, catalog),
        OUT_GO: _gofmt(gen_go(schema, catalog)),
        OUT_TS: gen_ts(schema, catalog),
    }
    check = "--check" in sys.argv
    stale: list[str] = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            if check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale generated contract files (run gen_types.py):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
