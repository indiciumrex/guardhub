package accuracy

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Scorecard is the machine-readable result (docs/accuracy/scorecard.json and
// packages/shared/accuracy.json, which the API reads to gate enabling a module).
type Scorecard struct {
	Version int          `json:"version"`
	Source  string       `json:"source"` // git revision the lab ran on
	Gate    GateSpec     `json:"gate"`
	Targets []string     `json:"targets"`
	Checks  []CheckScore `json:"checks"`
}

// GateSpec records the thresholds the scorecard was judged with.
type GateSpec struct {
	MinPrecision float64 `json:"min_precision"`
	MinRecall    float64 `json:"min_recall"`
	MinPositives int     `json:"min_positives"`
	MinCleanRuns int     `json:"min_clean_runs"`
}

// NewScorecard bundles scores with the gate they were judged against.
func NewScorecard(source string, manifests []Manifest, scores []CheckScore) Scorecard {
	var targets []string
	for _, m := range manifests {
		targets = append(targets, m.Target)
	}
	sort.Strings(targets)
	return Scorecard{
		Version: 1, Source: source, Targets: targets, Checks: scores,
		Gate: GateSpec{MinPrecision: MinPrecision, MinRecall: MinRecall, MinPositives: MinPositives, MinCleanRuns: MinCleanRuns},
	}
}

// Write renders scorecard.json, README.md (summary) and one <check_id>.md
// per check into dir. Output is deterministic for identical input.
func Write(dir string, sc Scorecard) error {
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // docs directory
		return err
	}
	raw, err := json.MarshalIndent(sc, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "scorecard.json"), append(raw, '\n'), 0o644); err != nil { //nolint:gosec // public docs
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "README.md"), []byte(summary(sc)), 0o644); err != nil { //nolint:gosec // public docs
		return err
	}
	for _, c := range sc.Checks {
		if err := os.WriteFile(filepath.Join(dir, c.CheckID+".md"), []byte(detail(sc, c)), 0o644); err != nil { //nolint:gosec // public docs
			return err
		}
	}
	return nil
}

func pct(v *float64) string {
	if v == nil {
		return "n/a"
	}
	return fmt.Sprintf("%.1f%%", *v*100)
}

func verdict(c CheckScore) string {
	if c.MeetsGate {
		return "meets the gate"
	}
	return "NOT measured well enough: " + strings.Join(c.GateNotes, "; ")
}

func summary(sc Scorecard) string {
	var b strings.Builder
	b.WriteString("# Check accuracy (validation lab)\n\n")
	b.WriteString("Generated by `scanner lab` from `test_corpus/` (do not edit by hand). ")
	fmt.Fprintf(&b, "Lab source revision: `%s`.\n\n", sc.Source)
	fmt.Fprintf(&b, "Gate for switching a check on: precision >= %.0f%%, recall >= %.0f%%, at least %d ground-truth findings, at least %d clean target, no check errors.\n\n",
		sc.Gate.MinPrecision*100, sc.Gate.MinRecall*100, sc.Gate.MinPositives, sc.Gate.MinCleanRuns)
	fmt.Fprintf(&b, "Targets: %s\n\n", strings.Join(sc.Targets, ", "))
	b.WriteString("| Check | Targets | TP | FP | FN | FN outside | Precision | Recall | Recall (all) | Gate |\n|---|---|---|---|---|---|---|---|---|---|\n")
	for _, c := range sc.Checks {
		gate := "yes"
		if !c.MeetsGate {
			gate = "no: " + strings.Join(c.GateNotes, "; ")
		}
		fmt.Fprintf(&b, "| [`%s`](%s.md) | %d | %d | %d | %d | %d | %s | %s | %s | %s |\n",
			c.CheckID, c.CheckID, c.Targets, c.TP, c.FP, c.FN, c.FNOutside, pct(c.Precision), pct(c.Recall), pct(c.RecallAll), gate)
	}
	b.WriteString("\nTP = expected finding reported; FP = reported but not in the ground truth; FN = expected but not reported. ")
	b.WriteString("FN outside = a real issue beyond what the check declares it covers (e.g. a product not in its catalogue); it lowers Recall (all), not the Recall the gate uses. ")
	b.WriteString("Ground truth lives in `test_corpus/manifests/` with a reason for every entry.\n")
	return b.String()
}

func detail(sc Scorecard, c CheckScore) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# `%s` accuracy\n\n", c.CheckID)
	fmt.Fprintf(&b, "Lab source revision `%s`. Verdict: **%s**.\n\n", sc.Source, verdict(c))
	fmt.Fprintf(&b, "| Precision | Recall | Recall (all) | TP | FP | FN | FN outside | Tolerated | Targets | Clean targets | Errors |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
	fmt.Fprintf(&b, "| %s | %s | %s | %d | %d | %d | %d | %d | %d | %d | %d |\n\n",
		pct(c.Precision), pct(c.Recall), pct(c.RecallAll), c.TP, c.FP, c.FN, c.FNOutside, c.Tolerated, c.Targets, c.CleanRuns, c.Errors)
	keys := make([]string, 0, len(c.ByKey))
	for k := range c.ByKey {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	if len(keys) > 0 {
		b.WriteString("## By finding\n\n| Finding key | TP | FP | FN |\n|---|---|---|---|\n")
		for _, k := range keys {
			s := c.ByKey[k]
			fmt.Fprintf(&b, "| `%s` | %d | %d | %d |\n", k, s.TP, s.FP, s.FN)
		}
		b.WriteString("\n")
	}
	section := func(title string, cs []Case) {
		fmt.Fprintf(&b, "## %s (%d)\n\n", title, len(cs))
		if len(cs) == 0 {
			b.WriteString("None.\n\n")
			return
		}
		for _, x := range cs {
			fmt.Fprintf(&b, "- `%s` / `%s`", x.Target, x.Key)
			if x.Location != "" {
				fmt.Fprintf(&b, " at `%s`", x.Location)
			}
			if x.Outside {
				b.WriteString(" (outside the declared scope)")
			}
			if x.Why != "" {
				fmt.Fprintf(&b, ": %s", x.Why)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	section("False positives", c.FalsePos)
	section("False negatives", c.FalseNeg)
	section("True positives", c.TruePos)
	return b.String()
}

// SharedGate is packages/shared/accuracy.json: what the API reads to refuse
// switching on a module whose accuracy was not measured well enough. It has
// no revision field so it only changes when a measurement changes (CI
// regenerates it and fails on any difference).
type SharedGate struct {
	Comment string                     `json:"$comment"`
	Version int                        `json:"version"`
	Gate    GateSpec                   `json:"gate"`
	Checks  map[string]SharedCheckGate `json:"checks"`
}

// SharedCheckGate is one check's measured accuracy.
type SharedCheckGate struct {
	MeetsGate bool     `json:"meets_gate"`
	Precision *float64 `json:"precision"`
	Recall    *float64 `json:"recall"`
	RecallAll *float64 `json:"recall_all"`
	TP        int      `json:"tp"`
	FP        int      `json:"fp"`
	FN        int      `json:"fn"`
	FNOutside int      `json:"fn_outside"`
	Targets   int      `json:"targets"`
}

// WriteShared writes the gate file (map keys are sorted by encoding/json).
func WriteShared(path string, sc Scorecard) error {
	g := SharedGate{
		Comment: "Generated by `scanner lab` (test_corpus/). Do not edit by hand. The API refuses to enable a module whose check is missing here or has meets_gate=false.",
		Version: 1, Gate: sc.Gate, Checks: map[string]SharedCheckGate{},
	}
	for _, c := range sc.Checks {
		g.Checks[c.CheckID] = SharedCheckGate{MeetsGate: c.MeetsGate, Precision: round(c.Precision), Recall: round(c.Recall),
			RecallAll: round(c.RecallAll), TP: c.TP, FP: c.FP, FN: c.FN, FNOutside: c.FNOutside, Targets: c.Targets}
	}
	raw, err := json.MarshalIndent(g, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(raw, '\n'), 0o644) //nolint:gosec // public contract file
}

func round(v *float64) *float64 {
	if v == nil {
		return nil
	}
	r := float64(int(*v*10000+0.5)) / 10000
	return &r
}
